 function pages(){
   const result=[];
   let n=0;
   for(let p=1;p<=72;p++){
    const count=p===72?9:10;
    const positions=[];
    for(let i=1;i<=count;i++){
     const [article_no,description,unit,warning]=DATA[n++];
     positions.push({page:p,position:i,article_no,description,unit,location:'1025',
       counted_stock:null,verified:!warning,warning,beleg:p===1?'100021289':String(100021420+p-2)});
    }
    result.push({page:p,beleg:p===1?'100021289':String(100021420+p-2),positions,warnings:[]});
   }
   if(n!==EXPECTED_ROWS)throw Error('RONDO-Katalog unvollständig. Sicherheitsabbruch.');
   return result;
 }
